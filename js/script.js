const PAST_PAGE_SIZE = 6;

// =====================================================
//  LIGHTBOX (eventos passados)
// =====================================================
let _lbPhotos = [];
let _lbIndex  = 0;

function lbOpen(photos, index) {
    _lbPhotos = photos;
    _lbIndex  = index;
    _lbShow();
    document.body.style.overflow = 'hidden';
}

function _lbShow() {
    document.getElementById('evtLbImg').src = _lbPhotos[_lbIndex];
    document.getElementById('evtLbCounter').textContent = `${_lbIndex + 1} / ${_lbPhotos.length}`;
    document.getElementById('evtLightbox').classList.add('active');
}

function lbClose() {
    document.getElementById('evtLightbox').classList.remove('active');
    document.body.style.overflow = '';
}

function lbNav(dir) {
    _lbIndex = (_lbIndex + dir + _lbPhotos.length) % _lbPhotos.length;
    _lbShow();
}

document.addEventListener('keydown', function(e) {
    const lb = document.getElementById('evtLightbox');
    if (!lb || !lb.classList.contains('active')) return;
    if (e.key === 'ArrowRight') lbNav(1);
    if (e.key === 'ArrowLeft')  lbNav(-1);
    if (e.key === 'Escape')     lbClose();
});

// =====================================================
//  RENDERIZAÇÃO DE EVENTS
// =====================================================
function initEvents() {

    const upcoming = EVENTS_DATA.filter(e => e.status === 'upcoming');
    const past     = EVENTS_DATA.filter(e => e.status === 'past');

    const upcomingCount = document.getElementById('upcoming-count');
    const pastCount     = document.getElementById('past-count');
    if (upcomingCount) upcomingCount.textContent = upcoming.length;
    if (pastCount)     pastCount.textContent     = past.length;

    // ── Próximos ──
    const gridUpcoming  = document.getElementById('grid-upcoming');
    const emptyUpcoming = document.getElementById('empty-upcoming');

    if (gridUpcoming) {
        if (upcoming.length === 0) {
            gridUpcoming.style.display = 'grid';
            if (emptyUpcoming) emptyUpcoming.style.display = 'none';
            gridUpcoming.innerHTML = renderComingSoonCard(currentLang);
            gridUpcoming.querySelectorAll('.event-card').forEach(el => el.classList.add('visible'));
        } else {
            gridUpcoming.innerHTML = upcoming.map(e => renderUpcomingCard(e, currentLang)).join('');
            gridUpcoming.querySelectorAll('.event-card').forEach(el => {
                el.classList.add('visible');
            });
        }
    }

    // ── Anteriores com paginação ──
    const gridPast     = document.getElementById('grid-past');
    const emptyPast    = document.getElementById('empty-past');
    const loadMoreWrap = document.getElementById('load-more-wrap');
    const loadMoreBtn  = document.getElementById('load-more-btn');

    let pastPage = 0;

    function renderPastPage() {
        if (!gridPast) return;

        if (past.length === 0) {
            gridPast.style.display = 'none';
            if (emptyPast) emptyPast.style.display = 'block';
            return;
        }

        const slice = past.slice(pastPage * PAST_PAGE_SIZE, (pastPage + 1) * PAST_PAGE_SIZE);

        slice.forEach(event => {
            const div = document.createElement('div');
            div.innerHTML = renderPastCard(event);
            const card = div.firstElementChild;
            gridPast.appendChild(card);
            card.classList.add('visible');

            if (event.gallery && event.gallery.length > 0) {
                card.addEventListener('click', () => lbOpen(event.gallery, 0));
            }
        });

        pastPage++;

        const hasMore = past.length > pastPage * PAST_PAGE_SIZE;
        if (loadMoreWrap) loadMoreWrap.style.display = hasMore ? 'block' : 'none';
    }

    renderPastPage();
    if (loadMoreBtn) loadMoreBtn.addEventListener('click', renderPastPage);

    // Expõe função de re-render para ser chamada por changeLanguage
    window.rerenderUpcomingCards = function() {
        const grid = document.getElementById('grid-upcoming');
        if (!grid) return;
        const up = EVENTS_DATA.filter(e => e.status === 'upcoming');
        if (up.length === 0) {
            grid.innerHTML = renderComingSoonCard(currentLang);
        } else {
            grid.innerHTML = up.map(e => renderUpcomingCard(e, currentLang)).join('');
        }
        grid.querySelectorAll('.event-card').forEach(el => el.classList.add('visible'));
    };

    // ── Toggle de abas ──
    const tabs   = document.querySelectorAll('.events-tab');
    const panels = document.querySelectorAll('.events-panel');

    // Se não há próximos eventos, ativa aba "Edições Anteriores" por padrão
    if (upcoming.length === 0 && past.length > 0) {
        tabs.forEach(t => t.classList.remove('active'));
        panels.forEach(p => p.classList.remove('active'));
        const pastTab   = document.querySelector('.events-tab[data-tab="past"]');
        const pastPanel = document.getElementById('panel-past');
        if (pastTab)   pastTab.classList.add('active');
        if (pastPanel) pastPanel.classList.add('active');
    }

    tabs.forEach(tab => {
        tab.addEventListener('click', function () {
            tabs.forEach(t => t.classList.remove('active'));
            panels.forEach(p => p.classList.remove('active'));
            this.classList.add('active');
            const panel = document.getElementById('panel-' + this.dataset.tab);
            if (panel) panel.classList.add('active');
        });
    });

}

