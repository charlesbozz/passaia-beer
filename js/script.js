// Recupera valor aninhado de um objeto usando notação de ponto
function getTranslation(lang, key) {
    const keys = key.split('.');
    let value = translations[lang];
    for (const k of keys) {
        if (value && value[k] !== undefined) {
            value = value[k];
        } else {
            return key; // fallback: retorna a própria chave
        }
    }
    return value;
}

// Aplica traduções a todos os elementos [data-i18n]
// Só altera elementos sem filhos HTML para não quebrar estrutura do DOM
// Idioma ativo (atualizado por changeLanguage)
let currentLang = 'pt';

// Helper: retorna string localizada de um campo que pode ser string ou { pt, en, it }
function localField(field, lang) {
    if (!field) return '';
    if (typeof field === 'string') return field;
    return field[lang] || field['pt'] || '';
}

function changeLanguage(lang) {
    currentLang = lang;

    document.querySelectorAll('[data-i18n]').forEach(element => {
        const key = element.getAttribute('data-i18n');
        const translation = getTranslation(lang, key);

        if (element.children.length === 0) {
            element.textContent = translation;
        }
    });

    localStorage.setItem('preferredLanguage', lang);
    document.documentElement.lang = lang === 'pt' ? 'pt-BR' : lang;

    // Re-renderiza cards de eventos com o novo idioma
    if (typeof rerenderUpcomingCards === 'function') rerenderUpcomingCards();
}

